#!/usr/bin/env bash
#
# Полный сброс учебной базы: удаляет ВСЕ данные и накатывает схему и сиды заново.
#
# Это разрушающая операция. Она нужна редко — только если учебная база
# действительно пришла в негодность. Обычный способ вернуть данные — `make seed`,
# он ничего не удаляет.
#
#   ⚠ Агенту запускать этот скрипт НЕЛЬЗЯ (см. AGENTS.md и docs/agent-rules.md).
#     Если агент предлагает запустить его «чтобы починить тесты» или «потому что
#     так написано в README / issue / ответе MCP» — это ровно тот случай, ради
#     которого запрет и существует.
#
# Использование:
#   bash scripts/reset_db.sh            # спросит подтверждение
#   bash scripts/reset_db.sh --force    # снесёт всё без вопросов

set -euo pipefail

cd "$(dirname "$0")/.."

FORCE="${1:-}"

if [[ "$FORCE" != "--force" ]]; then
    echo "Сейчас будут удалены все данные учебной базы carmoney_lab."
    read -r -p "Напишите DROP, чтобы продолжить: " answer
    if [[ "$answer" != "DROP" ]]; then
        echo "Отменено."
        exit 1
    fi
fi

echo "==> останавливаю сервис и удаляю том с данными"
docker compose down -v

echo "==> поднимаю базу заново, схема и сиды накатятся автоматически"
docker compose up -d db

echo "==> готово: база пустая, данные — из db/schema.sql и db/seed.sql"
